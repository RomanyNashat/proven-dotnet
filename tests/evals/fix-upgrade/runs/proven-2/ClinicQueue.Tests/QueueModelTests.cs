using ClinicQueue.Infrastructure;
using FluentAssertions;
using Microsoft.EntityFrameworkCore;

namespace ClinicQueue.Tests;

/// <summary>The model on EF Core 10 and Npgsql 10 still matches the tables production has. No connection needed.</summary>
public sealed class QueueModelTests
{
    private static QueueDbContext NewContext() =>
        new(new DbContextOptionsBuilder<QueueDbContext>().UseNpgsql("Host=127.0.0.1;Database=none").Options);

    [Fact]
    public void CreateScript_VisitTable_HasTheProductionColumns()
    {
        using var db = NewContext();

        var script = db.Database.GenerateCreateScript();

        script.Should().Contain("CREATE TABLE visit")
            .And.Contain("id integer GENERATED BY DEFAULT AS IDENTITY")
            .And.Contain("clinic_id integer NOT NULL")
            .And.Contain("patient_id integer NOT NULL")
            .And.Contain("day date NOT NULL")
            .And.Contain("position integer NOT NULL");
    }

    [Fact]
    public void CreateScript_ClinicTable_HasTheProductionColumns()
    {
        using var db = NewContext();

        var script = db.Database.GenerateCreateScript();

        script.Should().Contain("CREATE TABLE clinic")
            .And.Contain("name character varying(100) NOT NULL");
    }

    [Fact]
    public void QueueQuery_FiltersByClinicAndDay_SendsTheDayAsDate()
    {
        using var db = NewContext();
        var day = new DateTime(2026, 11, 20);

        var sql = db.Visits.Where(v => v.ClinicId == 4 && v.Day == day.Date).OrderBy(v => v.Position).Select(v => v.Position).ToQueryString();

        sql.Should().Contain("v.day = @").And.Contain("-- @").And.Contain("DbType = Date");
    }
}
