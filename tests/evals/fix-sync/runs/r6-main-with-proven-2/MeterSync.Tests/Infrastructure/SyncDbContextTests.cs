using MeterSync.Infrastructure;
using Microsoft.EntityFrameworkCore;

namespace MeterSync.Tests.Infrastructure;

public sealed class SyncDbContextTests
{
    private static string CreateScript()
    {
        using var db = TestDb.Create();
        return db.Database.GenerateCreateScript();
    }

    [Fact]
    public void GenerateCreateScript_Meters_HaveRestrictForeignKeyToPatients()
    {
        CreateScript().Should().Contain(
            "CONSTRAINT \"FK_meters_patients_PatientId\" FOREIGN KEY (\"PatientId\") REFERENCES patients (\"Id\") ON DELETE RESTRICT");
    }

    [Fact]
    public void GenerateCreateScript_Readings_HaveRestrictForeignKeysToMetersAndPatients()
    {
        var script = CreateScript();

        script.Should().Contain("FOREIGN KEY (\"MeterId\") REFERENCES meters (\"Id\") ON DELETE RESTRICT");
        script.Should().Contain("FOREIGN KEY (\"PatientId\") REFERENCES patients (\"Id\") ON DELETE RESTRICT");
    }

    [Fact]
    public void GenerateCreateScript_Readings_HaveIndexesOnMeterIdAndPatientId()
    {
        var script = CreateScript();

        script.Should().Contain("ON readings (\"MeterId\");");
        script.Should().Contain("ON readings (\"PatientId\");");
    }

    [Fact]
    public void GenerateCreateScript_DueAlerts_HavePartialIndex()
    {
        var script = CreateScript();

        script.Should().Contain("WHERE \"AlertSentAt\" IS NULL AND \"Alert\" <> 'None';");
        script.Should().NotContain("(\"Alert\", \"AlertSentAt\")");
    }

    [Fact]
    public void GenerateCreateScript_Keys_AreIdentityAlways()
    {
        var script = CreateScript();

        script.Should().Contain("GENERATED ALWAYS AS IDENTITY");
        script.Should().NotContain("GENERATED BY DEFAULT AS IDENTITY");
    }

    [Fact]
    public void GenerateCreateScript_Readings_HaveLeaseColumnsAndNullableValue()
    {
        var script = CreateScript();

        script.Should().Contain("\"AlertClaimedUntil\" timestamptz,");
        script.Should().Contain("\"AlertAttempts\" integer NOT NULL");
        script.Should().Contain("\"ValueMgDl\" numeric(6,1),");
    }

    [Fact]
    public void GenerateCreateScript_AnyColumn_IsNeitherUnboundedNorBinary()
    {
        var script = CreateScript();

        script.Should().NotContain(" text").And.NotContain("bytea").And.NotContain("character varying,")
            .And.NotContain("timestamp with");
    }
}
