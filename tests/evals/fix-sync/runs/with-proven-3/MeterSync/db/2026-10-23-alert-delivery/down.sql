-- Only after the previous version is running again. The index statements run outside a transaction.
SET lock_timeout = '5s';

CREATE INDEX CONCURRENTLY IF NOT EXISTS "IX_readings_Alert_AlertSentAt" ON readings ("Alert", "AlertSentAt");
DROP INDEX CONCURRENTLY IF EXISTS ix_readings_pending_alerts;
DROP INDEX CONCURRENTLY IF EXISTS "IX_meters_SerialKey";
DROP INDEX CONCURRENTLY IF EXISTS "IX_readings_PatientId";
DROP INDEX CONCURRENTLY IF EXISTS "IX_readings_MeterId";

BEGIN;
ALTER TABLE readings DROP CONSTRAINT IF EXISTS "FK_readings_patients_PatientId";
ALTER TABLE readings DROP CONSTRAINT IF EXISTS "FK_readings_meters_MeterId";
ALTER TABLE meters DROP CONSTRAINT IF EXISTS "FK_meters_patients_PatientId";

ALTER TABLE patients ALTER COLUMN "Id" SET GENERATED BY DEFAULT;
ALTER TABLE meters ALTER COLUMN "Id" SET GENERATED BY DEFAULT;
ALTER TABLE readings ALTER COLUMN "Id" SET GENERATED BY DEFAULT;

ALTER TABLE meters DROP COLUMN IF EXISTS "SerialKey";
-- Alerts still pending go back to the old sweeper's rule (Alert <> 'None' AND AlertSentAt IS NULL), so
-- parked and history readings would be sent by the old version: mark them sent-at-epoch to keep them quiet.
UPDATE readings SET "AlertSentAt" = 'epoch' WHERE "AlertDelivery" IN ('NotNeeded', 'Failed') AND "Alert" <> 'None' AND "AlertSentAt" IS NULL;
ALTER TABLE readings DROP COLUMN IF EXISTS "AlertLastError";
ALTER TABLE readings DROP COLUMN IF EXISTS "AlertClaimedUntil";
ALTER TABLE readings DROP COLUMN IF EXISTS "AlertAttempts";
ALTER TABLE readings DROP COLUMN IF EXISTS "AlertDelivery";
COMMIT;
